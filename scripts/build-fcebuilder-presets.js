#!/usr/bin/env node
/**
 * build-fcebuilder-presets.js
 *
 * Regenerates fcebuilder/presets.js (the builder's offline preset catalog) from
 * the per-boss source files, in manifest order. Emitted in the historic
 * { en: [...], ru: [...] } shape so the builder's existing load code is unchanged.
 *
 * Run after adding/editing bosses (or from the pipeline) so the builder's preset
 * dropdown matches the site.
 */
const fs = require("fs");
const path = require("path");

const FCE_DIR = path.join(__dirname, "..", "datamine", "fce");
const DATA_DIR = path.join(FCE_DIR, "data");
const BOSSES_DIR = path.join(DATA_DIR, "bosses");
const INDEX_PATH = path.join(DATA_DIR, "fce-index.json");
const OUT_PATH = path.join(__dirname, "..", "datamine-builder", "fce", "presets.js");

// Shared layout/art fields carried on the EN (base) preset entry.
const SHARED_KEYS = [
  "boss_id", "source_psd", "art", "art_object_position", "name_color",
  "art_scale", "art_x", "art_y",
  "name_y", "name_right", "name_width", "name_scale",
  "copy_width", "copy_y", "copy_scale"
];

function readJson(file) {
  try { return JSON.parse(fs.readFileSync(file, "utf8")); } catch (e) { return null; }
}

function build() {
  const index = readJson(INDEX_PATH) || { bosses: [] };
  const en = [];
  const ru = [];

  for (const entry of index.bosses || []) {
    const boss = readJson(path.join(BOSSES_DIR, `${entry.slug}.json`));
    if (!boss) continue;

    const enEntry = { slug: boss.slug, name: (boss.en && boss.en.name) || boss.slug };
    for (const key of SHARED_KEYS) {
      if (boss[key] !== undefined && boss[key] !== null) enEntry[key] = boss[key];
    }
    enEntry.mechanics = ((boss.en && boss.en.mechanics) || []).map((m) => ({
      index: m.index || "", html: m.html || ""
    }));
    en.push(enEntry);

    ru.push({
      slug: boss.slug,
      name: (boss.ru && boss.ru.name) || (boss.en && boss.en.name) || boss.slug,
      boss_id: boss.boss_id || undefined,
      mechanics: ((boss.ru && boss.ru.mechanics) || []).map((m) => ({
        index: m.index || "", html: m.html || ""
      }))
    });
  }

  const banner =
    "// AUTO-GENERATED by scripts/build-fcebuilder-presets.js from datamine/fce/data/bosses/*.json.\n" +
    "// Do not edit by hand; edit the per-boss files and rerun the script.\n";
  const body = "window.FCE_PRESETS = " + JSON.stringify({ en, ru }, null, 2) + ";\n";
  fs.writeFileSync(OUT_PATH, banner + body, "utf8");
  console.log(`[fce-presets] Wrote ${en.length} presets -> ${path.relative(process.cwd(), OUT_PATH)}`);
}

if (require.main === module) build();
module.exports = { build };
